export type Dict = typeof ua;

/* Англійська частина — у ./i18n-en.ts і приходить окремим запитом, коли
   її обрали (див. loadEn і src/lib/lang.tsx). Доки файл не завантажено,
   `i18n.en` дивиться на українські рядки, тож звертання `i18n[lang]` ніколи
   не падає; сам перемикач показує EN лише тоді, коли рядки вже тут. */
export const i18n: Record<Lang, Dict> = { ua, en: ua };

let enLoading: Promise<void> | null = null;

export function isLangReady(lang: Lang) {
  return lang === "ua" || i18n.en !== ua;
}

export function loadEn(): Promise<void> {
  enLoading ??= import("./i18n-en").then((m) => {
    i18n.en = m.en;
  });
  return enLoading;
}
